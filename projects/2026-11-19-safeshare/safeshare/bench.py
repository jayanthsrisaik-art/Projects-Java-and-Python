"""Multi-seed benchmark: privacy vs utility for each release method."""

from __future__ import annotations

import json
import statistics
import time
from pathlib import Path

from .evaluate import evaluate
from .policy import load_policy
from .pseudonym import DEMO_KEY
from .release import run_release
from .synth import generate

POLICY = Path(__file__).resolve().parent.parent / "samples" / "policy.json"

ARMS = [  # (label, method, k, l)
    ("drop identifiers only", "none", 5, 1),
    ("full-domain k=5", "full_domain", 5, 1),
    ("mondrian k=5", "mondrian", 5, 1),
    ("mondrian k=5 tight boxes", "mondrian_tight", 5, 1),
    ("full-domain k=5 l=3", "full_domain", 5, 3),
    ("mondrian k=5 l=3", "mondrian", 5, 3),
    ("mondrian k=10 l=3", "mondrian", 10, 3),
]
METRICS = [("unique_reid", "attack"), ("mean_risk", "attack"), ("max_risk", "attack"),
           ("risk_gt_0.2", "attack"), ("attr_disclosure", "attack"),
           ("false_unique", "attack"), ("endpoint_exposure", "attack"),
           ("avg_ncp", "release"),
           ("suppressed_subjects", "release"), ("median_rel_error", "utility"),
           ("p90_rel_error", "utility"), ("seconds", "release")]


def run_bench(seeds: int, patients: int, work: str, out: str) -> dict:
    work_p, out_p = Path(work), Path(out)
    out_p.mkdir(parents=True, exist_ok=True)
    rows = []
    for seed in range(seeds):
        data = work_p / f"seed{seed}" / "clinic"
        info = generate(data, patients, seed)
        for label, method, k, l_div in ARMS:
            pol = load_policy(POLICY, k, l_div)
            rel = work_p / f"seed{seed}" / f"release_{method}_k{k}_l{l_div}"
            t0 = time.perf_counter()
            rep = run_release(data, pol, rel, DEMO_KEY, method, demo_key=True)
            secs = time.perf_counter() - t0
            ev = evaluate(data, rel, info["voters_path"], pol, DEMO_KEY, seed=seed)
            row = {"seed": seed, "arm": label,
                   "release": {**rep, "seconds": secs}, **ev}
            rows.append(row)
            a = ev["attack"]
            print(f"seed {seed} {label:24s} uniq={a['unique_reid']:.3f} "
                  f"risk={a['mean_risk']:.3f} disc={a['attr_disclosure']:.3f} "
                  f"ncp={rep['avg_ncp']:.3f} qerr={ev['utility']['median_rel_error']:.3f} "
                  f"supp={rep['suppressed_subjects']} {secs:.1f}s", flush=True)
    summary = {}
    for label, *_ in ARMS:
        arm_rows = [r for r in rows if r["arm"] == label]
        summary[label] = {}
        for m, section in METRICS:
            vals = [float(r[section][m]) for r in arm_rows]
            summary[label][m] = {"mean": statistics.mean(vals),
                                 "std": statistics.pstdev(vals),
                                 "min": min(vals), "max": max(vals)}
    result = {"seeds": seeds, "patients": patients, "summary": summary,
              "runs": [{"seed": r["seed"], "arm": r["arm"], "attack": r["attack"],
                        "utility": r["utility"],
                        "release": {k: r["release"][k] for k in
                                    ("avg_ncp", "suppressed_subjects", "verified",
                                     "class_stats", "full_domain_levels", "seconds")}}
                       for r in rows]}
    (out_p / "bench.json").write_text(json.dumps(result, indent=2) + "\n")
    (out_p / "bench.md").write_text(_markdown(result))
    print(_markdown(result))
    return result


def _markdown(res: dict) -> str:
    head = ("| method | unique re-id | mean risk | max risk | risk > 0.2 | "
            "diagnosis disclosed | false unique | endpoint exposure | avg NCP | suppressed | "
            "query err (median) | query err (p90) | release s |")
    lines = [f"# safeshare benchmark ({res['seeds']} seeds x {res['patients']} "
             "synthetic patients)", "",
             "Mean over seeds (min-max in brackets for the attack columns). "
             "Generated by `python -m safeshare bench`.", "", head,
             "|" + "---|" * 13]
    for label, s in res["summary"].items():
        def f(m, rng=False, digits=3):
            v = s[m]
            txt = f"{v['mean']:.{digits}f}"
            if rng:
                txt += f" [{v['min']:.{digits}f}-{v['max']:.{digits}f}]"
            return txt
        lines.append(f"| {label} | {f('unique_reid', True)} | {f('mean_risk', True)} | "
                     f"{f('max_risk')} | {f('risk_gt_0.2')} | "
                     f"{f('attr_disclosure', True)} | {f('false_unique')} | "
                     f"{f('endpoint_exposure')} | "
                     f"{f('avg_ncp')} | {f('suppressed_subjects', digits=1)} | "
                     f"{f('median_rel_error')} | {f('p90_rel_error')} | "
                     f"{f('seconds', digits=2)} |")
    return "\n".join(lines) + "\n"
